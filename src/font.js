// 35 pixels do not fit in a u32, so every glyph becomes two words: the first
// four rows (20 bits) and the last three (15 bits).
const SPLIT_ROW = 4;
const HI_BITS = SPLIT_ROW * COLS;
const LO_BITS = (ROWS - SPLIT_ROW) * COLS;

function pack(pattern) {
  const bits = pattern.replace(/ /g, "");
  if (bits.length !== ROWS * COLS) {
    throw new Error(`glyph must be ${ROWS * COLS} pixels, got ${bits.length}`);
  }
  let hi = 0;
  let lo = 0;
  for (let i = 0; i < bits.length; i++) {
    if (bits[i] !== "1") continue;
    if (i < HI_BITS) hi |= 1 << (HI_BITS - 1 - i);
    else lo |= 1 << (LO_BITS - 1 - (i - HI_BITS));
  }
  return [hi >>> 0, lo >>> 0];
}

const PACKED = Object.fromEntries(
  Object.entries(TABLE).map(([char, pattern]) => [char, pack(pattern)]),
);

// Unknown characters fall back to a space rather than throwing, so a repo name
// with an emoji in it still renders something sensible.
export function packString(text) {
  return [...text.toUpperCase()].map((char) => PACKED[char] ?? PACKED[" "]);
}

